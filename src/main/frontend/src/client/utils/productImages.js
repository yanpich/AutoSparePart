// ============================================
// PRODUCT DATA WITH IMAGES
// ============================================
export const getProductWithImages = (product) => {
  const categoryImageMap = {
    'Brake System': productImages.brakePads,
    'Engine Parts': productImages.oilFilter,
    'Electrical': productImages.carBattery,
    'Suspension': productImages.shockAbsorber,
    'Cooling System': productImages.radiator,
    'Exhaust': productImages.exhaustPipe,
    'Interior': productImages.seatCover,
    'Exterior': productImages.headlight,
    'Wheels & Tires': productImages.alloyWheel,
    'Fluids': productImages.engineOil,
    'Tools': productImages.toolSet
  }

  const image = categoryImageMap[product.category?.name] || productImages.default

  return {
    ...product,
    image: product.image || image,
    images: product.images || [image, productImages.default]
  }
}

// ============================================
// GENERATE PRODUCTS WITH IMAGES
// ============================================
export const generateProductsWithImages = (products) => {
  return products.map(product => getProductWithImages(product))
}

